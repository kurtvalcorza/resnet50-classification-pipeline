import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTEBOOK = ROOT / "tutorials" / "DIMER_Modern_Image_Classification_Workshop.ipynb"
LOCK = ROOT / "tools" / "modern-image-workshop-requirements.lock"
CELL_ID = "uv-install"
PIECE_LIMIT = 1000
MANAGED_PYTHON = "3.12.12"
UV_URL = (
    "https://files.pythonhosted.org/packages/1e/fd/432451d732917c49152a291de3ef171aa6b0f1a22d39780fb2c1f085ca4c/"
    "uv-0.12.15-py3-none-manylinux_2_17_x86_64.manylinux2014_x86_64.whl"
)
