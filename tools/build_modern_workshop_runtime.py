def pieces(text: str, limit: int = PIECE_LIMIT) -> list[str]:
    """Split at line boundaries into runs of at most ``limit`` characters (a longer line is cut)."""
    out: list[str] = []
    current = ""
    for line in text.splitlines(keepends=True):
        while len(line) > limit:
            if current:
                out.append(current)
                current = ""
            out.append(line[:limit])
            line = line[limit:]
        if current and len(current) + len(line) > limit:
            out.append(current)
            current = ""
        current += line
    if current:
        out.append(current)
    return out


def lock_text() -> str:
    data = LOCK.read_bytes()
    if b"\r" in data:
        raise SystemExit(f"{LOCK} must use LF line endings")
    return data.decode("utf-8")


def locked_packages(text: str) -> int:
    return len(re.findall(r"^[A-Za-z0-9][A-Za-z0-9._-]*==", text, flags=re.MULTILINE))


def cell_source(text: str) -> str:
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    head = HEAD.format(
        managed=MANAGED_PYTHON,
        url=UV_URL,
        uv_bytes=UV_BYTES,
        uv_sha=UV_SHA256,
        lock_sha=digest,
        locked=locked_packages(text),
    )
    body = "\n".join(f"    {piece!r}" for piece in pieces(text))
    return head + body + TAIL


def render(notebook: dict) -> dict:
    text = lock_text()
    cells = [c for c in notebook["cells"] if c.get("id") == CELL_ID]
    if len(cells) != 1:
        raise SystemExit(f"expected exactly one cell with id {CELL_ID!r}, found {len(cells)}")
    cells[0]["source"] = cell_source(text).splitlines(keepends=True)
    notebook["metadata"]["dimer"]["carried_files"] = {
        "requirements.lock.txt": {
            "source": LOCK.relative_to(ROOT).as_posix(),
            "sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
            "locked_packages": locked_packages(text),
        }
    }
    return notebook


def dump(notebook: dict) -> str:
    return json.dumps(notebook, indent=2, ensure_ascii=False)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the notebook setup cell is stale")
    args = parser.parse_args(argv)
    current = NOTEBOOK.read_text(encoding="utf-8")
    expected = dump(render(json.loads(current)))
    if args.check:
        if current != expected:
            print(f"STALE: {NOTEBOOK.name} setup cell differs from {LOCK.name}; run without --check")
            return 1
        print(f"OK: {NOTEBOOK.name} setup cell matches {LOCK.name}")
        return 0
    NOTEBOOK.write_bytes(expected.encode("utf-8"))
    print(f"wrote {NOTEBOOK.name} ({len(expected.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
