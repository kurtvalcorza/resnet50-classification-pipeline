"""Write or check the isolated-environment setup cell of the modern image classification workshop.

The workshop notebook builds its own environment instead of installing into the kernel: a size- and
SHA-256-verified ``uv`` wheel creates a managed CPython 3.12.12 venv and installs the carried hash lock
(``tools/modern-image-workshop-requirements.lock``, ``uv pip compile --generate-hashes`` for CPython 3.12
on ``x86_64-manylinux_2_28``) with ``--require-hashes --only-binary :all:``. The next cell routes every
later code cell to one persistent worker process running that venv's interpreter.

The lock is carried as an implicitly concatenated run of pieces of at most 1,000 characters, split at
line boundaries, so no notebook line is long enough to stall the Colab editor. Only the setup cell
(id ``uv-install``) and ``metadata.dimer.carried_files`` are touched; the workshop has no other generator.

Usage::

    python tools/build_modern_workshop_runtime.py          # rewrite the setup cell
    python tools/build_modern_workshop_runtime.py --check  # exit 1 if the notebook is stale
"""

